const norm = (s) => s.toLowerCase().replace(/[^0-9a-zа-яё]/gi, "");
// файлы и в корне, и уже разложенные по папкам разделов
const files = [];
for (const entry of fs.readdirSync(DIR, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith(".md") && !entry.name.startsWith("_")) files.push(entry.name);
  if (entry.isDirectory()) {
    for (const f of fs.readdirSync(path.join(DIR, entry.name))) if (f.endsWith(".md")) files.push(path.join(entry.name, f));
  }
}
const used = new Set();
const lines = ["# Сбежавшая нейросеть — оглавление", "", "> Порядок и разделы — как у автора. ⏳ — статья ещё не сохранена.", ""];
const missing = [];

for (const [folder, titles] of sections) {
  fs.mkdirSync(path.join(DIR, folder), { recursive: true });
  lines.push(`## ${folder.replace(/^\d+ /, "")}`, "");
  titles.forEach((title, i) => {
    const key = norm(title);
    const base = (f) => norm(path.basename(f).replace(/\.md$/, ""));
    const file = files.find((f) => !used.has(f) && (key.startsWith(base(f)) || base(f).startsWith(key)));
    if (file) {
      used.add(file);
      const name = path.basename(file);
      const target = path.join(folder, name);
      if (file !== target) fs.renameSync(path.join(DIR, file), path.join(DIR, target));
      lines.push(`${i + 1}. [[${folder}/${name.replace(/\.md$/, "")}|${title}]]`);
    } else {
      missing.push(title);
      lines.push(`${i + 1}. ⏳ ${title}`);
    }
  });
  lines.push("");
}

const extra = files.filter((f) => !used.has(f));
if (extra.length) {
  lines.push("## Вне разделов автора", "");
  extra.forEach((f) => lines.push(`- [[${f.replace(/\.md$/, "")}]]`));
  lines.push("");
}
fs.writeFileSync(path.join(DIR, "_Оглавление.md"), lines.join("\n"), "utf8");
console.log(`Разложено: ${used.size}, не сохранено: ${missing.length}, вне разделов: ${extra.length}`);
missing.forEach((m) => console.log("  ⏳ " + m));
extra.forEach((e) => console.log("  ? " + e));
